const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ids = ["sidebarAiForm", "sidebarAiStatus", "aiSetting-provider", "aiSetting-openaiKey", "aiSetting-openaiModel", "aiSetting-geminiKey", "aiSetting-geminiModel", "aiSetting-autoHighlightPrompt", "aiSetting-prompt", "aiSetting-usePreview", "aiSetting-selectionOnly", "aiSetting-deepResearch", "sidebarCategoryList", "sidebarAddCategory", "sidebarResetCategories", "sidebarPalette", "sidebarFontScale", "sidebarAddColor", "sidebarNewColor", "syncSettings"];
const nodes = new Map(ids.map((id) => [id, { value: "", checked: false, style: {}, children: [], handlers: {}, addEventListener(name, fn) { this.handlers[name] = fn; }, replaceChildren() { this.children = []; }, appendChild(item) { this.children.push(item); }, setAttribute() {} }]));
const data = { hkAISettings: { provider: "chatgpt", categories: [{ name: "Existing", color: "#ffffff" }], usePreview: true, unrelated: "preserve" } };
const listeners = [];
const storage = { get: async (key) => ({ [key]: structuredClone(data[key]) }), set: async (values) => { Object.assign(data, structuredClone(values)); } };
const document = { getElementById: (id) => nodes.get(id), querySelector: () => null, querySelectorAll: () => [], documentElement: { style: { setProperty() {} } }, createElement: () => ({ style: {}, append() {}, addEventListener() {}, setAttribute() {} }) };
const window = { document, chrome: { storage: { local: storage, onChanged: { addListener(fn) { listeners.push(fn); } } } }, HkI18n: { t: (key) => key } };
const context = { window, document, chrome: window.chrome, structuredClone, console };
vm.createContext(context);
vm.runInContext(fs.readFileSync(require.resolve("../sidebar-settings.js"), "utf8"), context);
(async () => {
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(nodes.get("aiSetting-provider").value, "chatgpt");
  nodes.get("aiSetting-provider").value = "openai";
  nodes.get("aiSetting-openaiKey").value = "secret";
  await nodes.get("sidebarAiForm").handlers.submit({ preventDefault() {} });
  assert.equal(data.hkAISettings.provider, "openai");
  assert.equal(data.hkAISettings.openaiKey, "secret");
  assert.equal(data.hkAISettings.unrelated, "preserve");
  assert.deepEqual(data.hkAISettings.categories, [{ name: "Existing", color: "#ffffff" }]);
  assert.equal(nodes.get("sidebarAiStatus").textContent, "sidebar.settingsSaved");
  nodes.get("sidebarAddCategory").handlers.click();
  await nodes.get("sidebarAiForm").handlers.submit({ preventDefault() {} });
  assert.equal(nodes.get("sidebarAiStatus").textContent, "sidebar.invalidCategories");
  assert.deepEqual(data.hkAISettings.categories, [{ name: "Existing", color: "#ffffff" }]);
  console.log("Sidebar settings UI passed: save preserves existing settings and invalid input is rejected.");
})().catch((error) => { console.error(error); process.exitCode = 1; });
